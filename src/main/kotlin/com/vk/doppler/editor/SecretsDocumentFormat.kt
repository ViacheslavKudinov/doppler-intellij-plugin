package com.vk.doppler.editor

import com.vk.doppler.cli.DopplerReservedSecrets
import com.vk.doppler.cli.DopplerSecret
import com.vk.doppler.cli.DopplerSecretNames
import org.yaml.snakeyaml.DumperOptions
import org.yaml.snakeyaml.LoaderOptions
import org.yaml.snakeyaml.Yaml
import org.yaml.snakeyaml.constructor.SafeConstructor
import org.yaml.snakeyaml.error.MarkedYAMLException
import org.yaml.snakeyaml.error.YAMLException
import org.yaml.snakeyaml.nodes.MappingNode
import org.yaml.snakeyaml.nodes.Node
import org.yaml.snakeyaml.nodes.ScalarNode
import org.yaml.snakeyaml.nodes.Tag
import org.yaml.snakeyaml.representer.Representer

class SecretsFormatException(
    message: String,
) : Exception(message)

/**
 * The result of reading the editor document.
 *
 * [values] maps a secret to its text, or to `null` when the document still carries the literal
 * `null` that marks a restricted secret. [cleared] holds secrets whose value was emptied out
 * (`KEY:`), which is the gesture for deleting them.
 */
data class ParsedSecrets(
    val values: Map<String, String?>,
    val cleared: Set<String>,
)

/**
 * Converts between Doppler secrets and the YAML document shown in the editor, matching the
 * format used by Doppler's own VS Code extension.
 *
 * A `null` value means the secret is restricted: it can be overwritten but not read back.
 */
object SecretsDocumentFormat {
    val HEADER: String =
        """
        #################################################################
        ##  This file was generated by Doppler. When you make          ##
        ##  changes to this file, they will be saved to your           ##
        ##  config in Doppler as well.                                 ##
        ##                                                             ##
        ##  A `null` value indicates that the secret is restricted.    ##
        ##  Restricted secrets may be overwritten but cannot be read.  ##
        #################################################################
        """.trimIndent()

    fun serialize(secrets: List<DopplerSecret>): String = serialize(secrets.associate { it.name to it.raw })

    fun serialize(secrets: Map<String, String?>): String {
        val sorted = secrets.toSortedMap()
        val document =
            HEADER + "\n\n" +
                sorted.entries.joinToString("") { (name, value) ->
                    renderEntry(name, value)
                }
        // Safety net: the hand-built block scalars must read back byte-identically,
        // otherwise fall back to the emitter's own always-correct quoting.
        return if (parsesBackTo(document, secrets)) document else HEADER + "\n\n" + dumpAll(sorted)
    }

    private fun renderEntry(
        name: String,
        value: String?,
    ): String {
        val emitted = dumpAll(mapOf(name to value))
        if (value == null || !value.contains('\n')) return emitted
        // snakeyaml refuses literal blocks for values containing tabs, which Doppler secrets
        // (JSON blobs, certificates) routinely do. Prefer a readable block when it round-trips.
        return buildLiteralBlock(name, value) ?: emitted
    }

    private fun buildLiteralBlock(
        name: String,
        value: String,
    ): String? {
        if (!DopplerSecretNames.isValid(name)) return null
        val lines = value.split("\n")
        // Trailing spaces and leading indentation are not preserved unambiguously by a block.
        if (lines.any { it != it.trimEnd() }) return null
        if (lines.first().startsWith(" ") || lines.first().startsWith("\t")) return null

        val chomping: String
        val contentLines: List<String>
        when {
            value.endsWith("\n\n") -> {
                return null
            }

            value.endsWith("\n") -> {
                chomping = "|"
                contentLines = lines.dropLast(1)
            }

            else -> {
                chomping = "|-"
                contentLines = lines
            }
        }

        val body = contentLines.joinToString("\n") { if (it.isEmpty()) "" else "  $it" }
        return "$name: $chomping\n$body\n"
    }

    private fun parsesBackTo(
        document: String,
        expected: Map<String, String?>,
    ): Boolean = runCatching { parseValues(document) == expected }.getOrDefault(false)

    private fun dumpAll(secrets: Map<String, String?>): String {
        if (secrets.isEmpty()) return ""
        val ordered = LinkedHashMap<String, String?>()
        secrets.toSortedMap().forEach { (name, value) -> ordered[name] = value }
        return newDumper().dump(ordered)
    }

    /**
     * Parses the edited document.
     *
     * @throws SecretsFormatException when the document is not a flat mapping of scalars, so an
     * unparseable buffer never results in a destructive push.
     */
    fun parse(text: String): ParsedSecrets {
        val root =
            try {
                newLoader().compose(java.io.StringReader(text))
            } catch (e: YAMLException) {
                val mark = (e as? MarkedYAMLException)?.problemMark
                val location = mark?.let { " at line ${it.line + 1}, column ${it.column + 1}" }.orEmpty()
                throw SecretsFormatException("Document is not valid YAML$location.")
            } ?: return ParsedSecrets(emptyMap(), emptySet())

        if (root !is MappingNode) {
            throw SecretsFormatException("Expected a YAML mapping of secret names to values.")
        }

        val values = LinkedHashMap<String, String?>()
        val cleared = LinkedHashSet<String>()

        for (entry in root.value) {
            val keyNode =
                entry.keyNode as? ScalarNode
                    ?: throw SecretsFormatException("Secret names must be plain text.")
            val name = keyNode.value.orEmpty()
            if (name.isBlank()) {
                throw SecretsFormatException("Secret names cannot be empty.")
            }
            if (!DopplerSecretNames.isValid(name)) {
                // Never echo the text: a mistyped line may well be a pasted secret value.
                throw SecretsFormatException(
                    "Invalid secret name at line ${keyNode.startMark.line + 1}. " +
                        "Use only letters, digits, _, /, :, ., and -.",
                )
            }
            if (DopplerReservedSecrets.isReserved(name)) {
                throw SecretsFormatException("'$name' is managed by Doppler and cannot be edited.")
            }
            if (name in values || name in cleared) {
                throw SecretsFormatException("Secret '$name' is listed more than once.")
            }

            val valueNode =
                entry.valueNode as? ScalarNode
                    ?: throw SecretsFormatException("Secret '$name' must be a single value, not a list or mapping.")

            // `KEY:` with nothing after it is a deliberate clear; the literal `KEY: null`
            // is how a restricted secret is rendered and must be left untouched.
            when {
                valueNode.tag == Tag.NULL && valueNode.value.isEmpty() -> cleared += name
                valueNode.tag == Tag.NULL -> values[name] = null
                else -> values[name] = valueNode.value
            }
        }
        return ParsedSecrets(values, cleared)
    }

    private fun parseValues(text: String): Map<String, String?> = parse(text).values

    private fun newLoader(): Yaml {
        val options =
            LoaderOptions().apply {
                // SafeConstructor plus an alias cap: the document is user-editable, so never
                // construct arbitrary types and never expand billion-laughs style aliases.
                maxAliasesForCollections = 50
                isAllowDuplicateKeys = false
            }
        return Yaml(SafeConstructor(options))
    }

    private fun newDumper(): Yaml {
        val options =
            DumperOptions().apply {
                defaultFlowStyle = DumperOptions.FlowStyle.BLOCK
                indent = 2
                // Long secrets must never be wrapped: folding would corrupt the value.
                splitLines = false
                width = Int.MAX_VALUE
            }
        return Yaml(MultilineLiteralRepresenter(options), options)
    }

    /** Renders multi-line secrets as `|-` blocks instead of escaped one-liners. */
    private class MultilineLiteralRepresenter(
        options: DumperOptions,
    ) : Representer(options) {
        override fun representScalar(
            tag: Tag,
            value: String,
            style: DumperOptions.ScalarStyle?,
        ): Node {
            val effective = if (value.contains('\n')) DumperOptions.ScalarStyle.LITERAL else style
            return super.representScalar(tag, value, effective)
        }
    }
}
