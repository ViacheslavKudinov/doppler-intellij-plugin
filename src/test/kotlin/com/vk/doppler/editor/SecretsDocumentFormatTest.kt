package com.vk.doppler.editor

import com.vk.doppler.cli.DopplerSecret
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test

class SecretsDocumentFormatTest {
    private fun secret(
        name: String,
        raw: String?,
    ) = DopplerSecret(name, raw, raw, null)

    private fun parseValues(text: String) = SecretsDocumentFormat.parse(text).values

    @Test
    fun `document starts with the doppler header`() {
        val text = SecretsDocumentFormat.serialize(listOf(secret("A", "1")))
        assertTrue(text, text.startsWith("####"))
        assertTrue(text, text.contains("This file was generated by Doppler"))
        assertTrue(text, text.contains("A `null` value indicates that the secret is restricted."))
    }

    @Test
    fun `round trips values that would break dotenv parsing`() {
        val secrets =
            listOf(
                secret("MULTILINE", "-----BEGIN KEY-----\nabc\n-----END KEY-----"),
                secret("WITH_HASH", "pa#ss word"),
                secret("WITH_QUOTES", """he said "hi""""),
                secret("WITH_COLON", "psql://app@localhost/appdb"),
                secret("EMPTY", ""),
                secret("REFERENCE", "\${DOPPLER_ENVIRONMENT}"),
                secret("LEADING_SPACE", "  padded  "),
                secret("NUMERIC", "8080"),
                secret("BOOLISH", "true"),
                secret("NULLISH", "null"),
            )

        val parsed = parseValues(SecretsDocumentFormat.serialize(secrets))

        assertEquals(secrets.associate { it.name to it.raw }, parsed)
    }

    @Test
    fun `multiline secrets are written as literal blocks`() {
        val text = SecretsDocumentFormat.serialize(listOf(secret("PRIVATE_KEY", "line1\nline2\nline3")))
        assertTrue(text, text.contains("PRIVATE_KEY: |-"))
        assertTrue(text, text.contains("\n  line1\n  line2\n  line3"))
    }

    @Test
    fun `multiline values containing tabs still use literal blocks`() {
        val value = "{\n\t\"ENABLE_ANALYTICS\": true,\n\t\"MAX_ACCOUNTS\": 500\n}"
        val text = SecretsDocumentFormat.serialize(listOf(secret("FEATURE_FLAGS", value)))

        assertTrue(text, text.contains("FEATURE_FLAGS: |-"))
        assertEquals(mapOf("FEATURE_FLAGS" to value), parseValues(text))
    }

    @Test
    fun `awkward multiline values fall back to a form that still round trips`() {
        val awkward =
            listOf(
                "trailing spaces   \nsecond line",
                "ends with newline\n",
                "ends with blank line\n\n",
                "  leading indent\nsecond",
                "\ttab first\nsecond",
            )
        for (value in awkward) {
            val text = SecretsDocumentFormat.serialize(listOf(secret("X", value)))
            assertEquals(
                "round trip failed for ${value.replace("\n", "\\n")}",
                mapOf("X" to value),
                parseValues(text),
            )
        }
    }

    @Test
    fun `long values are never wrapped`() {
        val long = "sk_test_" + "x".repeat(400)
        val text = SecretsDocumentFormat.serialize(listOf(secret("STRIPE_KEY", long)))
        assertTrue(text, text.contains(long))
        assertEquals(mapOf("STRIPE_KEY" to long), parseValues(text))
    }

    @Test
    fun `restricted secrets round trip as null`() {
        val text = SecretsDocumentFormat.serialize(listOf(secret("RESTRICTED", null), secret("OPEN", "v")))
        assertTrue(text, text.contains("RESTRICTED: null"))
        assertEquals(mapOf("RESTRICTED" to null, "OPEN" to "v"), parseValues(text))
    }

    @Test
    fun `accepts the supported secret name characters`() {
        val parsed =
            parseValues(
                "1ABC: value\n-A: value\nA-B: value\nA/B: value\n\"A:B\": value\nA.B: value\nA_B: value",
            )

        assertEquals(setOf("1ABC", "-A", "A-B", "A/B", "A:B", "A.B", "A_B"), parsed.keys)
    }

    @Test
    fun `header only document parses to empty map`() {
        assertEquals(emptyMap<String, String?>(), parseValues(SecretsDocumentFormat.HEADER))
    }

    @Test
    fun `secrets are sorted by name`() {
        val text = SecretsDocumentFormat.serialize(listOf(secret("ZEBRA", "1"), secret("ALPHA", "2")))
        assertTrue(text, text.indexOf("ALPHA") < text.indexOf("ZEBRA"))
    }

    @Test
    fun `rejects malformed yaml`() {
        assertRejected("A: [unclosed")
    }

    @Test
    fun `yaml errors do not expose document contents or retain the parser exception`() {
        val secret = "SYNTHETIC_SECRET_MUST_NOT_REACH_NOTIFICATIONS"
        try {
            SecretsDocumentFormat.parse("API_KEY: [$secret")
            fail("Expected SecretsFormatException")
        } catch (expected: SecretsFormatException) {
            val message = requireNotNull(expected.message)
            assertTrue(message, message.startsWith("Document is not valid YAML at line "))
            assertFalse(message.contains(secret))
            assertFalse(message.contains("API_KEY"))
            assertNull(expected.cause)
        }
    }

    @Test
    fun `rejects non mapping root`() {
        assertRejected("- just\n- a\n- list")
    }

    @Test
    fun `rejects nested values`() {
        assertRejected("A:\n  b: 1")
        assertRejected("A:\n  - 1\n  - 2")
    }

    @Test
    fun `rejects duplicate keys`() {
        assertRejected("A: 1\nA: 2")
    }

    @Test
    fun `rejects secret names containing unsupported characters without echoing them`() {
        for (name in listOf("A=B", "\"WITH SPACE\"", "A@B")) {
            try {
                SecretsDocumentFormat.parse("OK: 1\n$name: value")
                fail("Expected SecretsFormatException for $name")
            } catch (expected: SecretsFormatException) {
                val message = requireNotNull(expected.message)
                assertTrue(message, message.startsWith("Invalid secret name at line 2"))
                assertFalse(message, message.contains(name.trim('"')))
            }
        }
    }

    @Test
    fun `rejects doppler managed secrets`() {
        assertRejected("DOPPLER_PROJECT: x")
    }

    @Test
    fun `does not construct arbitrary java types`() {
        assertRejected("A: !!java.net.URL [http://example.test]")
    }

    @Test
    fun `an emptied value is a clear, a literal null is not`() {
        val parsed =
            SecretsDocumentFormat.parse(
                """
                CLEARED:
                RESTRICTED: null
                TILDE: ~
                EMPTY_STRING: ""
                NORMAL: v
                """.trimIndent(),
            )

        assertEquals(setOf("CLEARED"), parsed.cleared)
        assertEquals(
            mapOf("RESTRICTED" to null, "TILDE" to null, "EMPTY_STRING" to "", "NORMAL" to "v"),
            parsed.values,
        )
    }

    private fun assertRejected(text: String) {
        try {
            SecretsDocumentFormat.parse(text)
            fail("Expected SecretsFormatException for: $text")
        } catch (expected: SecretsFormatException) {
            assertTrue(expected.message!!.isNotBlank())
        }
    }
}
